CELL_W, CELL_H = 8, 10
COLS = 16


def build_atlas():
    """Returns (atlas canvas, glyph list of dicts {char, x, y, w} with y measured from the atlas top)."""
    chars = sorted(_G.keys(), key=ord)
    rows = (len(chars) + COLS - 1) // COLS
    atlas = Canvas(COLS * CELL_W, max(16, rows * CELL_H))
    white = rgb("#ffffff")
    glyphs = []
    for i, ch in enumerate(chars):
        cx, cy = (i % COLS) * CELL_W, (i // COLS) * CELL_H
        rows_ = _G[ch]
        width = max(len(r) for r in rows_)
        for y, row in enumerate(rows_):
            for x, p in enumerate(row):
                if p == "#":
                    atlas.set(cx + x, cy + y, white)
        glyphs.append({"char": ch, "x": cx, "y": cy, "w": width})
    return atlas, glyphs


def measure(text):
    widths = {ch: max(len(r) for r in rows) for ch, rows in _G.items()}
    total = 0
    for ch in text:
        total += SPACE_ADVANCE + LETTER_SPACING if ch == " " else widths.get(ch, 3) + LETTER_SPACING
    return max(0, total - LETTER_SPACING)


def draw_text(canvas, text, x, y, color, shadow=None):
    """Draws text with its top-left at (x, y). Used for previews and baked labels."""
    for pass_color, off in ((shadow, 1), (color, 0)):
        if pass_color is None:
            continue
        cx = x
        for ch in text:
            if ch == " ":
                cx += SPACE_ADVANCE + LETTER_SPACING
                continue
            rows_ = _G.get(ch, _G["?"])
            for yy, row in enumerate(rows_):
                for xx, p in enumerate(row):
                    if p == "#":
                        canvas.set(cx + xx + off, y + yy + off, pass_color)
            cx += max(len(r) for r in rows_) + LETTER_SPACING
